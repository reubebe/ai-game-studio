import { useEffect, useRef, useState } from "react";
import { Field, IconButton, NumberInput } from "../../components/ui";
import { PlayIcon, StopIcon } from "../../components/icons";

/** A level's sound settings: looping music and imported files that replace built-in sounds by name. */
export interface LevelAudio {
  music?: { asset: string; volume: number } | undefined;
  sounds?: Partial<Record<string, string>> | undefined;
}

/** Drops empty parts, so a level with no sound settings keeps no `audio` at all. */
export function cleanAudio(a: LevelAudio): LevelAudio | undefined {
  const sounds = Object.fromEntries(Object.entries(a.sounds ?? {}).filter(([, v]) => v));
  const out: LevelAudio = {};
  if (a.music) out.music = a.music;
  if (Object.keys(sounds).length) out.sounds = sounds;
  return out.music || out.sounds ? out : undefined;
}

const label = (cue: string) => `${cue[0]!.toUpperCase()}${cue.slice(1)}`;

/**
 * Music and per-sound files for a level, with a preview button for each file. Built-in sounds are
 * generated by the game itself, so only files can be previewed here.
 */
export function AudioSettings({ audio, cues, files, assetUrl, godot, onChange }: { audio: LevelAudio | undefined; cues: readonly string[]; files: string[]; assetUrl: ((asset: string) => string | null) | undefined; godot: boolean; onChange: (next: LevelAudio | undefined) => void }) {
  const [playing, setPlaying] = useState<string | null>(null);
  const player = useRef<HTMLAudioElement | null>(null);
  useEffect(
    () => () => {
      player.current?.pause();
    },
    [],
  );
  const preview = (asset: string) => {
    player.current?.pause();
    if (playing === asset || !assetUrl) return setPlaying(null);
    const url = assetUrl(asset);
    if (!url) return;
    const a = new Audio(url);
    a.onended = () => setPlaying(null);
    a.play().then(
      () => setPlaying(asset),
      () => setPlaying(null),
    );
    player.current = a;
  };
  const current: LevelAudio = audio ?? {};
  const set = (next: LevelAudio) => onChange(cleanAudio(next));
  const option = (f: string) => <option key={f} value={f}>{f.replace(/^assets\//, "")}</option>;
  const previewButton = (asset: string | undefined, what: string) => (
    <IconButton
      small
      label={asset && playing === asset ? `Stop the ${what}` : `Play the ${what}`}
      tip={!asset ? "Choose a file first" : !assetUrl ? "Previews play in the desktop app" : undefined}
      disabled={!asset || !assetUrl}
      onClick={() => asset && preview(asset)}
    >
      {asset && playing === asset ? <StopIcon /> : <PlayIcon />}
    </IconButton>
  );
  return (
    <>
      <div className="section-label">Sound</div>
      <p className="xsmall muted" style={{ lineHeight: 1.5, margin: 0 }}>
        {!godot
          ? "Imported sounds play in Godot projects; Unity and Unreal keep their generated sounds."
          : files.length
            ? "Music loops while the level plays. A file chosen for a sound replaces the built-in one wherever the rules play it."
            : "Import sounds or music (.ogg, .wav or .mp3) in Assets, or add free ones from the library's Sounds, to use them here."}
      </p>
      <Field label="Music">
        <div className="row" style={{ gap: 6 }}>
          <select className="select" aria-label="Music" disabled={!godot || (!files.length && !current.music)} value={current.music?.asset ?? ""} onChange={(e) => set({ ...current, music: e.target.value ? { asset: e.target.value, volume: current.music?.volume ?? 0.6 } : undefined })}>
            <option value="">None</option>
            {current.music && !files.includes(current.music.asset) && <option value={current.music.asset}>{current.music.asset} (missing)</option>}
            {files.map(option)}
          </select>
          {previewButton(current.music?.asset, "music")}
        </div>
      </Field>
      {current.music && (
        <Field label="Music volume (%)" htmlFor="music-volume">
          <NumberInput id="music-volume" value={Math.round(current.music.volume * 100)} min={0} max={100} step={5} onCommit={(v) => set({ ...current, music: { ...current.music!, volume: v / 100 } })} />
        </Field>
      )}
      {cues.map((cue) => {
        const file = current.sounds?.[cue];
        return (
          <Field key={cue} label={`${label(cue)} sound`}>
            <div className="row" style={{ gap: 6 }}>
              <select className="select" aria-label={`${label(cue)} sound`} disabled={!godot || (!files.length && !file)} value={file ?? ""} onChange={(e) => set({ ...current, sounds: { ...current.sounds, [cue]: e.target.value || undefined } })}>
                <option value="">Built-in</option>
                {file && !files.includes(file) && <option value={file}>{file} (missing)</option>}
                {files.map(option)}
              </select>
              {previewButton(file, `${cue} sound`)}
            </div>
          </Field>
        );
      })}
    </>
  );
}
