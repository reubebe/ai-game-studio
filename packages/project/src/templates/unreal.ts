interface IniSection {
  name: string;
  lines: string[];
}

function parseIni(text: string): IniSection[] {
  const sections: IniSection[] = [{ name: "", lines: [] }];
  for (const line of text.replace(/\r\n/g, "\n").split("\n")) {
    const header = /^\[(.+)\]\s*$/.exec(line);
    if (header) sections.push({ name: header[1]!, lines: [] });
    else sections[sections.length - 1]!.lines.push(line);
  }
  return sections;
}

const iniKey = (line: string) => line.split("=", 1)[0]!.trim();

/**
 * Puts one Unreal ini file on top of another: a plain Key=Value replaces that key in the same section,
 * array lines (+Key, -Key, !Key, .Key) and comments are added after the base's own lines (Unreal reads a
 * file from top to bottom), and sections the base lacks are added at the end. Blank lines in the top file
 * are dropped.
 */
export function iniOverlay(base: string, top: string): string {
  const out = parseIni(base);
  for (const section of parseIni(top)) {
    const lines = section.lines.filter((l) => l.trim() !== "");
    if (section.name === "") {
      out[0]!.lines.unshift(...lines);
      continue;
    }
    let target = out.find((s) => s.name === section.name);
    if (!target) {
      target = { name: section.name, lines: [] };
      out.push(target);
    }
    while (target.lines.length > 0 && target.lines[target.lines.length - 1]!.trim() === "") target.lines.pop();
    for (const line of lines) {
      const plain = !/^[+\-!.;]/.test(line.trimStart());
      if (plain) target.lines = target.lines.filter((l) => /^\s*[+\-!.;]/.test(l) || iniKey(l) !== iniKey(line));
      target.lines.push(line);
    }
  }
  return renderIni(out);
}

function renderIni(sections: IniSection[]): string {
  const parts: string[] = [];
  for (const s of sections) {
    if (s.name) {
      if (parts.length > 0 && parts[parts.length - 1] !== "") parts.push("");
      parts.push(`[${s.name}]`);
    }
    // Trailing blank lines inside a section are dropped; one blank line separates sections.
    const lines = [...s.lines];
    while (lines.length > 0 && lines[lines.length - 1]!.trim() === "") lines.pop();
    parts.push(...lines);
  }
  return parts.join("\n").replace(/^\n+/, "") + "\n";
}

/** Removes base lines from one section, for settings of the sample that must not carry over. */
function dropIniLines(text: string, section: string, drop: (line: string) => boolean): string {
  const sections = parseIni(text);
  for (const s of sections) if (s.name === section) s.lines = s.lines.filter((l) => !drop(l));
  return renderIni(sections);
}

/**
 * The generated Unreal files with the sample's settings underneath: each of the sample's Config files is
 * the base and the game's file goes on top, except input, where the sample's Enhanced Input setup and
 * mouse capture are kept (its character looks around with the mouse). The sample's plugins join the
 * game's module in the .uproject. Its own demo level is not cooked, and its project id is not reused.
 */
export function withAnimationSample(files: GeneratedFile[], sample: UnrealSampleFiles): GeneratedFile[] {
  const configDir = `${UNREAL_DIR}/Config/`;
  const ours = new Map(files.filter((f) => f.path.startsWith(configDir)).map((f) => [f.path.slice(configDir.length), f.content]));
  const merged = new Map<string, string>();
  for (const [name, base] of Object.entries(sample.config)) {
    if (!/^[A-Za-z0-9_]+\.ini$/.test(name)) throw new Error(`Unexpected sample settings file ${name}`);
    let text = base;
    if (name === "DefaultGame.ini") {
      text = dropIniLines(text, "/Script/UnrealEd.ProjectPackagingSettings", (l) => /^\s*\+MapsToCook=/.test(l));
      text = dropIniLines(text, "/Script/EngineSettings.GeneralProjectSettings", (l) => iniKey(l) === "ProjectID");
    }
    const top = ours.get(name);
    if (top !== undefined && name !== "DefaultInput.ini") text = iniOverlay(text, top);
    if (name === "DefaultGame.ini") text = iniOverlay(text, UNREAL_REALISTIC_SETTINGS);
    if (name === "DefaultEngine.ini") {
      // The sample's switches for which character and body to use: its standard character (0) and Kellan (2).
      text = text
        .replace(/(Name="DDCvar\.PawnClass",[^)]*DefaultValueInt=)-?\d+/, "$10")
        .replace(/(Name="DDCvar\.VisualOverride",[^)]*DefaultValueInt=)-?\d+/, "$12");
    }
    merged.set(name, text);
  }
  for (const [name, text] of ours) if (!merged.has(name)) merged.set(name, name === "DefaultGame.ini" ? iniOverlay(text, UNREAL_REALISTIC_SETTINGS) : text);
  const uprojectPath = `${UNREAL_DIR}/${UNREAL_PROJECT}.uproject`;
  const theirs = JSON.parse(sample.uproject) as { Plugins?: Record<string, unknown>[] };
  // Each enabled plugin with the sample's limits (for example TargetAllowList ["Editor"] for editor-only tools).
  const LIMITS = ["TargetAllowList", "TargetDenyList", "PlatformAllowList", "PlatformDenyList"] as const;
  const names = (v: unknown) => Array.isArray(v) && v.every((x) => typeof x === "string" && /^[A-Za-z0-9_]+$/.test(x));
  const plugins: Record<string, unknown>[] = (theirs.Plugins ?? [])
    .filter((p) => typeof p["Name"] === "string" && /^[A-Za-z0-9_]+$/.test(p["Name"]) && p["Enabled"] === true)
    .map((p) => ({ Name: p["Name"] as string, Enabled: true, ...Object.fromEntries(LIMITS.filter((k) => names(p[k])).map((k) => [k, p[k]])) }));
  // The editor's Python and Geometry Script import Game Studio's trees and people on the first build
  // (src-tauri/assets/unreal_nature.py); editor only, so the game never carries them.
  for (const Name of NATURE_PLUGINS) if (!plugins.some((p) => p.Name === Name)) plugins.push({ Name, Enabled: true, TargetAllowList: ["Editor"] });
  return [
    ...files
      .filter((f) => !f.path.startsWith(configDir))
      .map((f) => (f.path === uprojectPath ? { path: f.path, content: json({ ...(JSON.parse(f.content) as object), Plugins: plugins }) } : f)),
    ...[...merged].map(([name, content]) => ({ path: `${configDir}${name}`, content })),
  ];
}

function generateUnreal(o: GenerateOptions, realistic: boolean): GeneratedProject {
  const version = o.engineVersion && UNREAL_VERSION_RE.test(o.engineVersion) ? o.engineVersion : UNREAL_VERSION;
  const world = sunCrystalValley();
  // The Godot game's clouds, ground patches and grass are not drawn by this engine's game.
  for (const k of GODOT_ONLY_ENVIRONMENT) delete world.environment[k];
  const graph = valleyRules();
  const manifest = baseManifest(o, {
    template: { id: realistic ? "exploration-unreal-realistic" : "exploration-unreal", version: "1.0.0" },
    genre: ["adventure", "exploration", "3d"],
    engine: { id: "unreal", version, projectDir: UNREAL_DIR },
    modules: ["core.rules", "game.exploration3d"],
    rules: [{ id: graph.id, path: `rules/${graph.id}.rules.json`, domain: "explore" }],
    data: [{ id: "world", path: "data/world.json", kind: "explore-world" }],
    portableFeatures: ["rules", "world-layout", "asset-index"],
  });
  const readme = `# ${manifest.title}

The Sun Crystal Valley level as an Unreal Engine ${version} project${realistic ? ", with a realistic person as the player" : ""}.

- **World** (\`data/world.json\`): edit it in Game Studio's world editor. Saving copies it to
  \`unreal/Content/GameStudioData/\`, which the game reads at startup and packaging ships as a loose file.
- **Rules** (\`rules/${graph.id}.rules.json\`): objectives, Elder Ama's dialogue and the shrine gate. Saving
  compiles them into the same folder, and the C++ rule runtime (\`Source/StudioValley/StudioRulesVM.h\`)
  runs them, as the Godot version and the studio's simulator do.
- **Unreal project** (\`unreal/${UNREAL_PROJECT}.uproject\`): a small C++ module in \`Source/StudioValley/\`
  builds the level from engine basic shapes, ${realistic ? "places the player" : "moves the player"} and connects the rules to the level.
- **Build** (Play view): compiles the module, cooks and packages an Apple silicon macOS app in
  \`exports/unreal-macos/\`, and can run its headless self-test. The first build compiles shaders and takes a while.
${
  realistic
    ? `
**Realistic people.** The player is the motion-matching character from Epic's free Game Animation Sample
(500+ motion-captured moves) wearing the sample's MetaHuman, Kellan, lit by Lumen under volumetric clouds.
Game Studio copied the sample's content from your copy in Documents/Unreal Projects into \`unreal/Content/\`
when it created this project. That content is Epic's, licensed for use in Unreal Engine projects; it is left
out of this project's snapshots (\`.gitignore\`). The character, controls and body are settings in
\`unreal/Config/DefaultGame.ini\` (\`[/Script/StudioValley.StudioGameMode]\`), on top of the sample's own
settings. The first build cooks the sample's animations and takes much longer than a plain valley.
`
    : ""
}
Needs Xcode (selected with xcode-select) and its Metal toolchain; Game Studio's Engines view checks both.

Controls: ${
    realistic
      ? "W A S D move, move the mouse to look around, Space jumps, Left Shift sprints, Left Ctrl walks, C crouches,\nE talks to people and reads signs."
      : "W A S D or arrows move, Shift sprints, Space jumps, hold the right mouse button to look around,\nE talks to people and reads signs."
  }
`;
  const rulesPath = `rules/${graph.id}.rules.json`;
  const sync = planEngineSync(manifest, { [rulesPath]: graph, "data/world.json": world }, createStudioRegistry());
  if (!sync.ok) throw new Error(`Template engine data failed: ${JSON.stringify(sync.problems)}`);
  const unrealIgnores = ["Binaries/", "Intermediate/", "Saved/", "DerivedDataCache/", "*.xcworkspace"].map((p) => `${UNREAL_DIR}/${p}`);
  // The sample's 7 GB of content stays out of snapshots; Game Studio's own data lives in GameStudioData.
  const sampleIgnores = realistic ? [`${UNREAL_DIR}/Content/*`, `!${UNREAL_DIR}/Content/GameStudioData/`] : [];
  const engineFiles = unrealTemplateFiles(manifest.title, version, manifest.projectId);
  return finalize(manifest, [
    ...commonFiles(manifest, readme, [...unrealIgnores, ...sampleIgnores, `${EXPORTS_DIR}/`]),
    { path: rulesPath, content: json(graph) },
    { path: "data/world.json", content: json(world) },
    ...(realistic ? withAnimationSample(engineFiles, o.unrealSample!) : engineFiles),
    ...sync.writes,
  ]);
}
