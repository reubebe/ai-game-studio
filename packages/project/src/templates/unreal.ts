const UNREAL_FILES = import.meta.glob("../../../../templates/exploration-unreal/unreal/**/*", { query: "?raw", import: "default", eager: true }) as Record<string, string>;
/** The C++ rule runtime (engine-addons/unreal), shipped into the game module next to the game code. */
const RULES_FILES = import.meta.glob("../../../../engine-addons/unreal/StudioRules/*.h", { query: "?raw", import: "default", eager: true }) as Record<string, string>;

/** The Unreal Engine release this template was built and tested with. */
export const UNREAL_VERSION = "5.8";
export const UNREAL_DIR = "unreal";
/** The C++ module and project are always called StudioValley; the title goes into the project settings. */
export const UNREAL_PROJECT = "StudioValley";
export const UNREAL_EXPORT_DIR = `${EXPORTS_DIR}/unreal-macos`;
const UNREAL_VERSION_RE = /^5\.\d{1,2}$/;

export function unrealTemplateFiles(title: string, version: string, projectId: string): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const [key, content] of Object.entries(UNREAL_FILES)) {
    const rel = key.split("/templates/exploration-unreal/unreal/")[1];
    if (!rel) continue;
    // ini values run to the end of the line, so the title is reduced to safe characters.
    const text = rel === "Config/DefaultGame.ini" ? content.replace("{{TITLE}}", exportAppName(title)) : rel === "Config/DefaultEngine.ini" ? content.replace("{{BUNDLE_ID}}", bundleIdFor(projectId)) : content;
    files.push({ path: `${UNREAL_DIR}/${rel}`, content: text });
  }
  for (const [key, content] of Object.entries(RULES_FILES)) {
    const name = key.split("/").pop();
    if (name) files.push({ path: `${UNREAL_DIR}/Source/${UNREAL_PROJECT}/${name}`, content });
  }
  files.push({
    path: `${UNREAL_DIR}/${UNREAL_PROJECT}.uproject`,
    content: json({
      FileVersion: 3,
      EngineAssociation: version,
      Category: "",
      Description: "Generated by Universal AI Game Studio",
      Modules: [{ Name: UNREAL_PROJECT, Type: "Runtime", LoadingPhase: "Default" }],
    }),
  });
  return files;
}

export function generateUnrealExploration(o: GenerateOptions): GeneratedProject {
  return generateUnreal(o, false);
}

/**
 * The same valley with realistic people: the player is the motion-matching character from Epic's free
 * Game Animation Sample, with its MetaHuman (Kellan) as the body, under Lumen light, clouds and fog.
 * Needs the sample on this computer (o.unrealSample); the app copies its content in after creating the files.
 */
export function generateUnrealRealistic(o: GenerateOptions): GeneratedProject {
  if (!o.unrealSample) throw new Error(`This template builds on Epic's free Game Animation Sample. ${UNREAL_SAMPLE_HOW_TO}`);
  const version = o.engineVersion && UNREAL_VERSION_RE.test(o.engineVersion) ? o.engineVersion : UNREAL_VERSION;
  let made: unknown;
  try {
    made = (JSON.parse(o.unrealSample.uproject) as { EngineAssociation?: unknown }).EngineAssociation;
  } catch {
    throw new Error("The Game Animation Sample's project file could not be read. Create the sample again in the Epic Games Launcher.");
  }
  // Its assets only open in the release they were saved with (or a later one).
  if (typeof made === "string" && made !== version) {
    throw new Error(`The Game Animation Sample on this Mac is for Unreal Engine ${made}, but this project would use Unreal Engine ${version}. In the Epic Games Launcher, create the sample again with version ${version}.`);
  }
  return generateUnreal(o, true);
}

